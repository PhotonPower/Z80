#!/usr/bin/env python3
"""Generates src/cpc_data.cpp (CPC firmware symbols and colour tables) from public reference tables.

Sources (names/addresses/colours are facts from the Amstrad CPC firmware documentation):
  * Bread80/Amstrad-CPC-BASIC-Source  Includes/JumpblockMain6128.asm  (after Dave Cantrell's firmware guide)
  * z88dk/z88dk                       lib/target/cpc/def/cpcfirm.def
  * floooh/chips                      chips/am40010.h                 (names of the 32 hardware colours)
  * john32b/djFlixel                  djFlixel/gfx/pal/Pal_CPC.hx      (RGB values of the 27 firmware inks)

All 212 entries present in both firmware tables agree. Both tables list SCR_FLOOD_BOX at &BC17, which
duplicates SCR_CHAR_LIMITS; &BC47 is the only unnamed slot of the main jump block and is where the
firmware manual puts SCR FLOOD BOX, so it is corrected here.

Usage: gen_cpc_data.py jumpblock.asm cpcfirm.def am40010.h Pal_CPC.hx > src/cpc_data.cpp
"""
import re
import sys

jumpblock, cpcfirm, am40010, palette = sys.argv[1:5]

a = {}
for line in open(jumpblock):
    m = re.match(r'^([A-Za-z_0-9]+)\s+EQU\s+\$([0-9A-Fa-f]+)', line)
    if m:
        a[m.group(1).upper()] = int(m.group(2), 16)
b = {}
for line in open(cpcfirm):
    m = re.match(r'\s*defc\s+([a-z_0-9]+)\s*=\s*\$([0-9a-fA-F]+)', line)
    if m:
        b[m.group(1).upper()] = int(m.group(2), 16)

rename = {'GRA_LLNE_ABSOLUTE': 'GRA_LINE_ABSOLUTE', 'KL_NEW_FRAMEFLY': 'KL_NEW_FRAME_FLY',
          'KL_ADD_FRAMEFLY': 'KL_ADD_FRAME_FLY', 'KL_DEL_FRAMEFLY': 'KL_DEL_FRAME_FLY', 'MC_JUMP_RESTORE': 'JUMP_RESTORE'}
merged = {}
for src in (a, b):
    for name, addr in src.items():
        name = rename.get(name, name)
        if name.startswith(('BIOS_', 'REAL_')) or name in ('BINARY_TO_REAL', 'INTEGER_TO_REAL'):
            continue  # AMSDOS BIOS and undocumented maths entries: only one source each, rarely needed
        if name in merged and merged[name] != addr:
            sys.exit(f'conflict for {name}')
        merged[name] = addr
merged['SCR_FLOOD_BOX'] = 0xBC47
# the generic aliases of the 6128 jump block (GRA_PLOT/GRA_TEST/GRA_LINE at BDDC..) are kept as they are

by_addr = {}
for name, addr in sorted(merged.items(), key=lambda kv: (kv[1], kv[0])):
    by_addr.setdefault(addr, []).append(name)
dups = {hex(k): v for k, v in by_addr.items() if len(v) > 1}
if dups:
    sys.exit(f'duplicate addresses: {dups}')

# colours: 32 hardware colours (names) and 27 firmware inks (RGB)
hw_names = []
blk = open(am40010).read()
blk = blk[blk.index('_am40010_cpc_colors[32]'):]
blk = blk[:blk.index('};')]
for line in blk.splitlines():
    m = re.search(r'//\s*#([0-9A-Fa-f]{2})\s+(.*)$', line)
    if m:
        hw_names.append((int(m.group(1), 16) - 0x40, m.group(2).strip().lower()))
inks = []
for line in open(palette):
    m = re.match(r'\s*0xFF([0-9A-F]{6}),?\s*//\s*(.*)$', line)
    if m:
        inks.append((m.group(1), m.group(2).strip().lower()))
assert len(hw_names) == 32 and len(inks) == 27
ink_of_name = {name: i for i, (_, name) in enumerate(inks)}
hw_rgb = [inks[ink_of_name[name]][0] for _, name in hw_names]
ink_to_hw = [None] * 27
for hw, name in hw_names:
    i = ink_of_name[name]
    if ink_to_hw[i] is None:
        ink_to_hw[i] = hw  # first of the duplicate hardware numbers
assert None not in ink_to_hw

print('// GENERATED by tools/gen/gen_cpc_data.py - do not edit by hand.')
print('// Sources and verification are described in that script.')
print('#include "z80/cpc.hpp"')
print()
print('namespace z80::cpc {')
print()
print('const std::array<PlatformSymbol, %d> kFirmwareSymbols = {{' % len(merged))
for addr, names in by_addr.items():
    print('    {"%s", 0x%04X},' % (names[0], addr))
print('}};')
print()
print('const std::array<std::uint32_t, 32> kHardwareColourRgb = {{')
for i in range(0, 32, 4):
    print('    ' + ', '.join('0x%s' % hw_rgb[j] for j in range(i, i + 4)) + ',')
print('}};')
print()
print('const std::array<std::uint8_t, 27> kInkToHardware = {{')
print('    ' + ', '.join(str(x) for x in ink_to_hw) + ',')
print('}};')
print()
print('const std::array<const char*, 32> kHardwareColourNames = {{')
for i in range(0, 32, 4):
    print('    ' + ', '.join('"%s"' % hw_names[j][1] for j in range(i, i + 4)) + ',')
print('}};')
print()
print('}  // namespace z80::cpc')
